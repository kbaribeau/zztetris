  function deepFreeze(value) {
    if (value && typeof value === "object") {
      for (const child of Object.values(value)) deepFreeze(child);
      Object.freeze(value);
    }
    return value;
  }
  function normalize(heights) {
    if (!Array.isArray(heights) || heights.length !== 4) return null;
    // Index explicitly so sparse arrays cannot pass Array.every's hole skipping.
    for (let x = 0; x < 4; x++)
      if (!Number.isSafeInteger(heights[x]) || heights[x] < 0) return null;
    const base = Math.min(...heights);
    return heights.map((h) => h - base);
  }
  function key(heights) {
    const profile = normalize(heights);
    return profile ? profile.join(",") : null;
  }
  // Each alternative is one complete resolution. All pieces within it are
  // required; repeats remain distinct. Unknown is not a dependency-free result.
  function validateDependencies(value) {
    if (!value || !Array.isArray(value.alternatives)) return false;
    if (value.status === "unknown") return value.alternatives.length === 0;
    if (value.status !== "known" || !value.alternatives.length) return false;
    for (const alternative of value.alternatives) {
      if (
        !alternative ||
        !Array.isArray(alternative.pieces) ||
        !["ordered", "unordered"].includes(alternative.order)
      )
        return false;
      if (
        typeof alternative.conditions !== "string" ||
        typeof alternative.evidence !== "string" ||
        !alternative.evidence.trim()
      )
        return false;
      for (const piece of alternative.pieces)
        if (typeof piece !== "string" || !/^[IJLOSTZ]$/.test(piece))
          return false;
    }
    return true;
  }
  const byKey = new Map(),
    ids = new Set();
  for (const contour of catalog) {
    if (
      key(contour.profile) !== contour.key ||
      Math.min(...contour.profile) !== 0 ||
      byKey.has(contour.key) ||
      ids.has(contour.id) ||
      !validateDependencies(contour.dependencies)
    )
      throw new Error("Invalid Left contour record: " + contour.id);
    ids.add(contour.id);
    byKey.set(contour.key, deepFreeze(contour));
  }
  // Four-height normalization and one indexed lookup; no catalog scan or search.
  // Invalid inputs and valid but unobserved contours both return null.
  function lookup(heights) {
    const k = key(heights);
    return k === null ? null : byKey.get(k) || null;
  }
